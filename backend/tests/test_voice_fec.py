import random
import re
import unittest
from pathlib import Path

from app.voice import fec


MMDVM_HOST_DIR = Path(__file__).resolve().parents[2] / "third_party" / "MMDVM-Host"


def _parse_table(source: str, name: str) -> list[int]:
    match = re.search(name + r"\[\]\s*=\s*\{(.*?)\};", source, re.S)
    if match is None:
        raise AssertionError(f"table {name} not found")
    return [int(token.rstrip("Uu"), 0) for token in re.findall(r"0x[0-9A-Fa-f]+U?|\d+U?", match.group(1))]


class GolayAndPrngTest(unittest.TestCase):
    def test_golay_23_12_known_vector(self):
        self.assertEqual(fec.golay_23_12_encode(1), 0xC75)

    def test_golay_24_12_has_even_weight(self):
        for value in range(4096):
            self.assertEqual(bin(fec.golay_24_12_encode(value)).count("1") % 2, 0)

    @unittest.skipUnless((MMDVM_HOST_DIR / "Golay24128.cpp").is_file(), "MMDVM-Host submodule not checked out")
    def test_matches_mmdvm_golay_tables(self):
        source = (MMDVM_HOST_DIR / "Golay24128.cpp").read_text(encoding="utf-8", errors="replace")
        table_23127 = _parse_table(source, "ENCODING_TABLE_23127")
        table_24128 = _parse_table(source, "ENCODING_TABLE_24128")
        for value in range(4096):
            self.assertEqual(fec.golay_23_12_encode(value), table_23127[value] >> 1, value)
            self.assertEqual(fec.golay_24_12_encode(value), table_24128[value], value)

    @unittest.skipUnless((MMDVM_HOST_DIR / "AMBEFEC.cpp").is_file(), "MMDVM-Host submodule not checked out")
    def test_matches_mmdvm_prng_table(self):
        source = (MMDVM_HOST_DIR / "AMBEFEC.cpp").read_text(encoding="utf-8", errors="replace")
        table = _parse_table(source, "PRNG_TABLE")
        self.assertEqual(len(table), 4096)
        for value in range(4096):
            self.assertEqual(fec.ambe_prng(value), table[value], value)


class AmbeFramingTest(unittest.TestCase):
    def test_round_trip_through_burst(self):
        rng = random.Random(1234)
        burst = bytearray(33)
        frames = [[rng.randint(0, 1) for _ in range(49)] for _ in range(3)]
        for index, bits in enumerate(frames):
            fec.place_dmr_ambe(burst, index, bits)
        for index, bits in enumerate(frames):
            a, b, c = fec.extract_dmr_ambe(burst, index)
            self.assertEqual(fec.abc_to_ambe49(a, b, c), bits)

    def test_voice_bits_avoid_sync_field(self):
        burst = bytearray(33)
        ones = [1] * 49
        for index in range(3):
            fec.place_dmr_ambe(burst, index, ones)
        # Bits 108..155 carry sync/EMB and are regenerated by MMDVM-Host.
        for position in range(108, 156):
            self.assertEqual(fec.read_bit(burst, position), 0)

    def test_tables_cover_each_position_once(self):
        positions = sorted(fec.DMR_A_TABLE + fec.DMR_B_TABLE + fec.DMR_C_TABLE)
        self.assertEqual(positions, list(range(72)))


class ReedSolomonTest(unittest.TestCase):
    @unittest.skipUnless((MMDVM_HOST_DIR / "RS129.cpp").is_file(), "MMDVM-Host submodule not checked out")
    def test_gf_tables_match_mmdvm(self):
        source = (MMDVM_HOST_DIR / "RS129.cpp").read_text(encoding="utf-8", errors="replace")
        exp_table = _parse_table(source, "EXP_TABLE")
        self.assertEqual(fec._GF_EXP[:255], exp_table[:255])

    def test_zero_message_has_zero_parity(self):
        self.assertEqual(fec.rs_12_9_parity(bytes(9)), bytes(3))


if __name__ == "__main__":
    unittest.main()
